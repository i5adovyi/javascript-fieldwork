import {build} from 'esbuild';
import {readFile,writeFile,readdir} from 'node:fs/promises';
import {resolve} from 'node:path';
const root=resolve(import.meta.dirname,'..');
await build({entryPoints:[resolve(root,'src/editor-entry.js')],outfile:resolve(root,'dist/code-editor.js'),bundle:true,format:'esm',target:'es2022',minify:true,legalComments:'none',banner:{js:'// CodeMirror 6 and Lezer, MIT licensed. See vendor/editor-LICENSES.txt. Generated by npm run editors:build.'}});
const packages=[];
for (const scope of ['@codemirror','@lezer']) {
  for (const name of (await readdir(resolve(root,'node_modules',scope))).sort()) packages.push(`${scope}/${name}`);
}
packages.push('@marijn/find-cluster-break','style-mod','w3c-keyname','crelt');
const licenses=[];
for (const name of packages) {
  const path=resolve(root,'node_modules',name);
  const pkg=JSON.parse(await readFile(resolve(path,'package.json'),'utf8'));
  licenses.push(`${name} ${pkg.version}\n${await readFile(resolve(path,'LICENSE'),'utf8')}`);
}
await writeFile(resolve(root,'dist/vendor/editor-LICENSES.txt'),licenses.join('\n---\n\n'));
console.log('Built the local JavaScript editor and third-party license notices.');
